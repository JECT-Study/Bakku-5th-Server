CREATE TABLE exchange_appointment
(
    id                               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange_id                      BIGINT           NOT NULL REFERENCES exchange (id),
    proposer_user_id                 BIGINT           NOT NULL,
    receiver_user_id                 BIGINT           NOT NULL,
    status                           VARCHAR(20)      NOT NULL,
    time_type                        VARCHAR(20)      NOT NULL,
    scheduled_at                     TIMESTAMPTZ,
    place_name                       VARCHAR(100)     NOT NULL,
    place_address                    VARCHAR(255),
    place_lat                        DOUBLE PRECISION NOT NULL,
    place_lng                        DOUBLE PRECISION NOT NULL,
    expires_at                       TIMESTAMPTZ      NOT NULL,
    proposer_reminder_offset_minutes INT,
    receiver_reminder_offset_minutes INT,
    confirmed_at                     TIMESTAMPTZ,
    created_at                       TIMESTAMPTZ      NOT NULL,
    updated_at                       TIMESTAMPTZ      NOT NULL,
    CONSTRAINT ck_exchange_appointment_status CHECK (status IN ('PROPOSED', 'REJECTED', 'WITHDRAWN', 'EXPIRED',
                                                                'AUTO_REJECTED', 'CONFIRMED', 'COMPLETED',
                                                                'NOT_MET', 'CANCELED')),
    CONSTRAINT ck_exchange_appointment_time_type CHECK (time_type IN ('NOW', 'SCHEDULED')),
    CONSTRAINT ck_exchange_appointment_scheduled_at CHECK (time_type = 'NOW' OR scheduled_at IS NOT NULL)
);

CREATE INDEX idx_exchange_appointment_exchange_id ON exchange_appointment (exchange_id);
CREATE INDEX idx_exchange_appointment_status_expires_at ON exchange_appointment (status, expires_at);

CREATE TABLE exchange_appointment_item
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT      NOT NULL REFERENCES exchange_appointment (id),
    offered_item_id BIGINT      NOT NULL REFERENCES exchange_offered_item (id),
    sort_order      INT         NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_exchange_appointment_item UNIQUE (appointment_id, offered_item_id)
);

CREATE INDEX idx_exchange_appointment_item_appointment_id_sort_order ON exchange_appointment_item (appointment_id, sort_order);
