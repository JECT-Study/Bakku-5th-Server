CREATE TABLE exchange_offered_item_image
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offered_item_id BIGINT       NOT NULL REFERENCES exchange_offered_item (id),
    image_key       VARCHAR(255) NOT NULL,
    sort_order      INT          NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_exchange_offered_item_image_item_sort_order UNIQUE (offered_item_id, sort_order),
    CONSTRAINT ck_exchange_offered_item_image_sort_order CHECK (sort_order BETWEEN 1 AND 5)
);
