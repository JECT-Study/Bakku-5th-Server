ALTER TABLE exchange_appointment
    ADD COLUMN resolved_at TIMESTAMPTZ;

CREATE TABLE exchange_appointment_confirmation
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT       NOT NULL REFERENCES exchange_appointment (id),
    user_id         BIGINT       NOT NULL,
    answer          VARCHAR(20)  NOT NULL,
    not_met_reason  VARCHAR(20),
    not_met_detail  VARCHAR(100),
    answered_at     TIMESTAMPTZ  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    -- 응답은 1인 1회 (F-01-1). 잠금을 지나쳐도 같은 사람의 두 번째 응답은 저장되지 않는다
    CONSTRAINT uk_exchange_appointment_confirmation UNIQUE (appointment_id, user_id),
    CONSTRAINT ck_exchange_appointment_confirmation_answer CHECK (answer IN ('DONE', 'NOT_MET')),
    CONSTRAINT ck_exchange_appointment_confirmation_reason CHECK (not_met_reason IS NULL OR not_met_reason IN
                                                                  ('NO_SHOW', 'SELF_ABSENT', 'ITEM_MISMATCH',
                                                                   'MONEY_DEMANDED', 'MUTUAL_CANCEL', 'OTHER'))
);
