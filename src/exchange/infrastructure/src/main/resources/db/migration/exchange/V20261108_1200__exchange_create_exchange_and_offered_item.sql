CREATE TABLE exchange
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT      NOT NULL,
    request_user_id BIGINT      NOT NULL,
    owner_id        BIGINT      NOT NULL,
    offer_type      VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    completed_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_exchange_offer_type CHECK (offer_type IN ('POST', 'NEW')),
    CONSTRAINT ck_exchange_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'CLOSED', 'LEFT'))
);

CREATE INDEX idx_exchange_post_id ON exchange (post_id);
CREATE INDEX idx_exchange_request_user_id ON exchange (request_user_id);
CREATE INDEX idx_exchange_owner_id ON exchange (owner_id);

CREATE TABLE exchange_offered_item
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange_id    BIGINT      NOT NULL REFERENCES exchange (id),
    type           VARCHAR(20) NOT NULL,
    source_post_id BIGINT,
    name           VARCHAR(40),
    item_condition VARCHAR(20),
    description    VARCHAR(1000),
    sort_order     INT         NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_exchange_offered_item_type CHECK (type IN ('POST', 'NEW')),
    CONSTRAINT ck_exchange_offered_item_condition CHECK (item_condition IN ('UNOPENED', 'OPENED'))
);

CREATE INDEX idx_exchange_offered_item_exchange_id_sort_order ON exchange_offered_item (exchange_id, sort_order);
CREATE INDEX idx_exchange_offered_item_source_post_id ON exchange_offered_item (source_post_id);
