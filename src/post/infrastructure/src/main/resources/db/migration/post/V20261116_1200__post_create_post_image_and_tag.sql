CREATE TABLE post
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id            BIGINT           NOT NULL,
    status               VARCHAR(20)      NOT NULL,
    title                VARCHAR(40)      NOT NULL,
    category             VARCHAR(20)      NOT NULL,
    is_opened            BOOLEAN          NOT NULL,
    description          VARCHAR(1000),
    wanted_item          VARCHAR(50),
    place_lat            DOUBLE PRECISION NOT NULL,
    place_lng            DOUBLE PRECISION NOT NULL,
    place_name           VARCHAR(100)     NOT NULL,
    place_region_name    VARCHAR(100)     NOT NULL,
    place_memo           VARCHAR(30),
    now_exchange_ends_at TIMESTAMPTZ,
    view_count           INT              NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ      NOT NULL,
    updated_at           TIMESTAMPTZ      NOT NULL,
    CONSTRAINT ck_post_status CHECK (status IN ('AVAILABLE', 'RESERVED', 'COMPLETED', 'DELETED')),
    CONSTRAINT ck_post_category CHECK (category IN ('CHARACTER', 'IDOL', 'SPORTS', 'ETC')),
    CONSTRAINT ck_post_view_count CHECK (view_count >= 0)
);

CREATE INDEX idx_post_author_id ON post (author_id);

CREATE TABLE post_image
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL REFERENCES post (id),
    image_key  VARCHAR(255) NOT NULL,
    sort_order INT          NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_post_image_post_id_sort_order UNIQUE (post_id, sort_order),
    CONSTRAINT ck_post_image_sort_order CHECK (sort_order BETWEEN 1 AND 5)
);

CREATE TABLE post_tag
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_post_tag_name UNIQUE (name)
);

CREATE TABLE post_tag_link
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT      NOT NULL REFERENCES post (id),
    tag_id     BIGINT      NOT NULL REFERENCES post_tag (id),
    sort_order INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_post_tag_link_post_id_tag_id UNIQUE (post_id, tag_id),
    CONSTRAINT uk_post_tag_link_post_id_sort_order UNIQUE (post_id, sort_order),
    CONSTRAINT ck_post_tag_link_sort_order CHECK (sort_order BETWEEN 1 AND 5)
);

CREATE INDEX idx_post_tag_link_tag_id ON post_tag_link (tag_id);
