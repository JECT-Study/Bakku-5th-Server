-- 예약 알림. 보낼 시각이 되면 1분 배치가 보내고 지운다 (결정 C4)
CREATE TABLE notification_scheduled
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_key VARCHAR(100),
    receiver_id  BIGINT      NOT NULL,
    type         VARCHAR(50) NOT NULL,
    sender_id    BIGINT,
    target_type  VARCHAR(20),
    target_id    BIGINT,
    params       TEXT        NOT NULL,
    fire_at      TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);

-- 같은 키 · 받는 사람은 한 건만 (다시 예약하면 교체). 키가 없으면 겹치지 않는다
CREATE UNIQUE INDEX uk_notification_scheduled_key_receiver ON notification_scheduled (schedule_key, receiver_id);

-- 보낼 시각이 지난 예약 찾기
CREATE INDEX idx_notification_scheduled_fire_at ON notification_scheduled (fire_at);
