-- 알림 목록. 채팅 메시지를 뺀 알림을 30일 보관한다 (X-01-1, 결정 C6)
CREATE TABLE notification_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_id BIGINT       NOT NULL,
    type        VARCHAR(50)  NOT NULL,
    title       VARCHAR(100) NOT NULL,
    body        VARCHAR(300) NOT NULL,
    target_type VARCHAR(20),
    target_id   BIGINT,
    read_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);

-- 목록은 받은 사람별 id 커서로 최신순 조회
CREATE INDEX idx_notification_history_receiver_id ON notification_history (receiver_id, id);

-- 안 읽은 수
CREATE INDEX idx_notification_history_unread ON notification_history (receiver_id) WHERE read_at IS NULL;
