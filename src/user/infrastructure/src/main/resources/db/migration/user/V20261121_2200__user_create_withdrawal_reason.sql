-- 탈퇴 사유 (선택). 서비스 개선용 통계라 회원 행과 따로 둔다 (G-09-2, 결정 A8)
CREATE TABLE user_withdrawal_reason
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT      NOT NULL REFERENCES user_member (id),
    reason       VARCHAR(30) NOT NULL,
    withdrawn_at TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_user_withdrawal_reason_reason CHECK (reason IN ('NO_WANTED_GOODS', 'HARD_TO_FIND_PARTNER', 'INCONVENIENT', 'OTHER'))
);
