-- 회원 차단. 한 사람이 같은 회원을 한 번만 차단한다 (C-09-2, 결정 C8)
CREATE TABLE user_block
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT      NOT NULL REFERENCES user_member (id),
    blocked_id BIGINT      NOT NULL REFERENCES user_member (id),
    blocked_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_user_block_not_self CHECK (blocker_id <> blocked_id)
);

-- 같은 차단은 한 행. 차단은 이 인덱스로 ON CONFLICT DO NOTHING 한다
CREATE UNIQUE INDEX uk_user_block_blocker_blocked ON user_block (blocker_id, blocked_id);

-- 나를 차단한 회원 조회 (차단 관계는 양방향)
CREATE INDEX idx_user_block_blocked_id ON user_block (blocked_id);
