-- 리프레시 토큰은 기기마다 한 행이다. 원문 대신 SHA-256 해시만 저장한다 (결정 C2)
CREATE TABLE user_refresh_token
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id           BIGINT       NOT NULL REFERENCES user_member (id),
    device_id           VARCHAR(100) NOT NULL,
    token_hash          VARCHAR(64)  NOT NULL,
    previous_token_hash VARCHAR(64),
    rotated_at          TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL
);

-- 기기 하나에 회원 하나. 다른 회원이 이 기기로 로그인하면 이 행을 새 회원 것으로 바꾼다 (결정 A12)
CREATE UNIQUE INDEX uk_user_refresh_token_device_id ON user_refresh_token (device_id);

-- 재발급 때 받은 토큰을 현재 · 직전 해시로 찾는다 (결정 C3)
CREATE UNIQUE INDEX uk_user_refresh_token_token_hash ON user_refresh_token (token_hash);
CREATE INDEX idx_user_refresh_token_previous_token_hash ON user_refresh_token (previous_token_hash);

-- 탈퇴 · 정지 때 회원의 토큰을 모두 지운다
CREATE INDEX idx_user_refresh_token_member_id ON user_refresh_token (member_id);
