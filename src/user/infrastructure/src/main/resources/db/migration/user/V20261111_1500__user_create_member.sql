CREATE TABLE user_member
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider             VARCHAR(10) NOT NULL,
    social_id_hash       VARCHAR(64),
    nickname             VARCHAR(10),
    birth_date           DATE,
    gender               VARCHAR(10),
    status               VARCHAR(20) NOT NULL,
    restricted_until     TIMESTAMPTZ,
    completed_count      INT         NOT NULL DEFAULT 0,
    marketing_agreed     BOOLEAN     NOT NULL,
    marketing_changed_at TIMESTAMPTZ NOT NULL,
    nickname_changed_at  TIMESTAMPTZ,
    previous_member_id   BIGINT REFERENCES user_member (id),
    withdrawn_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL,
    updated_at           TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_user_member_provider CHECK (provider IN ('KAKAO', 'NAVER', 'APPLE')),
    CONSTRAINT ck_user_member_gender CHECK (gender IN ('MALE', 'FEMALE')),
    CONSTRAINT ck_user_member_status CHECK (status IN ('ACTIVE', 'RESTRICTED', 'BANNED', 'WITHDRAWN')),
    CONSTRAINT ck_user_member_completed_count CHECK (completed_count >= 0)
);

-- 한 소셜 계정은 탈퇴하지 않은 회원 하나에만 연결된다. 탈퇴 회원 행은 1년 보관되므로 재가입하면 새 행이 생긴다 (결정 A4-3 · C9)
CREATE UNIQUE INDEX uk_user_member_provider_social_id_hash
    ON user_member (provider, social_id_hash)
    WHERE status <> 'WITHDRAWN';

-- 재가입 7일 확인 · 제재 이어서 적용은 탈퇴 회원 행도 찾아야 한다 (A-03-1)
CREATE INDEX idx_user_member_social_id_hash ON user_member (social_id_hash);

-- 닉네임은 영문 대소문자를 구분하지 않고 중복을 막는다. 탈퇴하면 비워지므로 다시 쓸 수 있다 (결정 A5-2 · C8)
CREATE UNIQUE INDEX uk_user_member_nickname ON user_member (lower(nickname));
