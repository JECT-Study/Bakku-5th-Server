-- 가입 때 받은 약관 동의 이력. 동의 일시 · 약관 버전을 남긴다 (A-04-1, 결정 A20)
CREATE TABLE user_terms_agreement
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT      NOT NULL REFERENCES user_member (id),
    terms_type    VARCHAR(30) NOT NULL,
    terms_version VARCHAR(20) NOT NULL,
    agreed        BOOLEAN     NOT NULL,
    agreed_at     TIMESTAMPTZ NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_user_terms_agreement_member_id ON user_terms_agreement (member_id);
