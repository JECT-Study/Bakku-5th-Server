-- 신고. 같은 신고자는 같은 대상을 한 번만 신고한다 (C-09-1, 결정 B11 · C8)
CREATE TABLE user_report
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id        BIGINT      NOT NULL REFERENCES user_member (id),
    target_type        VARCHAR(20) NOT NULL,
    target_id          BIGINT      NOT NULL,
    reason             VARCHAR(30) NOT NULL,
    detail             VARCHAR(300),
    -- 신고당한 회원. 1차는 회원 신고만 채우고 나머지는 2차에 대상 확인과 함께 채운다
    reported_member_id BIGINT REFERENCES user_member (id),
    reported_at        TIMESTAMPTZ NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL,
    updated_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_user_report_target_type CHECK (target_type IN ('POST', 'MEMBER', 'OFFERED_ITEM', 'CHAT_ROOM')),
    CONSTRAINT ck_user_report_reason CHECK (reason IN ('SALES_INDUCEMENT', 'EXTERNAL_TRADE', 'INAPPROPRIATE_CONTENT',
                                                       'FRAUD', 'ITEM_PROBLEM', 'OTHER'))
);

-- 같은 신고는 한 행. 신고는 이 인덱스로 ON CONFLICT DO NOTHING 한다
CREATE UNIQUE INDEX uk_user_report_reporter_target ON user_report (reporter_id, target_type, target_id);
