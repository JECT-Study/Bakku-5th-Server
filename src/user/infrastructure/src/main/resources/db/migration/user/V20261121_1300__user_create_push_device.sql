-- 푸시를 받을 기기. 기기 ID마다 한 행이고 로그아웃하면 지운다 (결정 A12, G-09-1)
CREATE TABLE user_push_device
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT       NOT NULL REFERENCES user_member (id),
    device_id   VARCHAR(100) NOT NULL,
    push_token  VARCHAR(512) NOT NULL,
    platform    VARCHAR(10)  NOT NULL,
    app_version VARCHAR(20),
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);

-- 기기 하나에 회원 하나. 등록은 이 인덱스로 upsert한다
CREATE UNIQUE INDEX uk_user_push_device_device_id ON user_push_device (device_id);

-- 같은 푸시 토큰이 두 기기 행에 있으면 다른 회원 알림이 잘못 간다 (결정 A12)
CREATE UNIQUE INDEX uk_user_push_device_push_token ON user_push_device (push_token);

-- 알림 발송 때 회원의 기기를 찾는다
CREATE INDEX idx_user_push_device_member_id ON user_push_device (member_id);
