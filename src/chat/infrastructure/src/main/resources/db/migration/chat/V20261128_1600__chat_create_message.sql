CREATE TABLE chat_message
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id            BIGINT      NOT NULL REFERENCES chat_room (id),
    sender_user_id          BIGINT,
    type                    VARCHAR(20) NOT NULL,
    text_content            VARCHAR(1000),
    external_trade_detected BOOLEAN,
    system_code             VARCHAR(50),
    system_text             VARCHAR(1000),
    system_link_type        VARCHAR(30),
    system_link_id          BIGINT,
    card_type               VARCHAR(50),
    card_target_id          BIGINT,
    client_message_id       VARCHAR(36),
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_chat_message_type CHECK (type IN ('TEXT', 'IMAGE', 'SYSTEM', 'CARD')),
    CONSTRAINT ck_chat_message_sender CHECK (
        (type IN ('TEXT', 'IMAGE') AND sender_user_id IS NOT NULL)
        OR (type IN ('SYSTEM', 'CARD') AND sender_user_id IS NULL AND client_message_id IS NULL)
    ),
    CONSTRAINT ck_chat_message_text CHECK (
        (type = 'TEXT' AND text_content IS NOT NULL)
        OR (type != 'TEXT' AND text_content IS NULL AND external_trade_detected IS NULL)
    ),
    CONSTRAINT ck_chat_message_system CHECK (
        (type = 'SYSTEM' AND system_code IS NOT NULL AND system_text IS NOT NULL)
        OR (type != 'SYSTEM' AND system_code IS NULL AND system_text IS NULL)
    ),
    CONSTRAINT ck_chat_message_system_link CHECK (
        (system_link_type IS NULL AND system_link_id IS NULL)
        OR (system_link_type IS NOT NULL AND system_link_id IS NOT NULL)
    ),
    CONSTRAINT ck_chat_message_card CHECK (
        (type = 'CARD' AND card_type IS NOT NULL AND card_target_id IS NOT NULL)
        OR (type != 'CARD' AND card_type IS NULL AND card_target_id IS NULL)
    )
);

CREATE INDEX idx_chat_message_chat_room_id_id ON chat_message (chat_room_id, id);
