CREATE TABLE chat_message_image
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT        NOT NULL REFERENCES chat_message (id),
    image_url  VARCHAR(2048) NOT NULL,
    sort_order INTEGER       NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_chat_message_image_message_id_sort_order UNIQUE (message_id, sort_order)
);

CREATE INDEX idx_chat_message_image_message_id ON chat_message_image (message_id);
