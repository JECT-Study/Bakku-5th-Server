CREATE TABLE chat_room
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange_id  BIGINT      NOT NULL,
    post_id      BIGINT      NOT NULL,
    requester_id BIGINT      NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_chat_room_exchange_id UNIQUE (exchange_id),
    CONSTRAINT uk_chat_room_post_id_requester_id UNIQUE (post_id, requester_id)
);

CREATE TABLE chat_participant
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT      NOT NULL REFERENCES chat_room (id),
    member_id    BIGINT      NOT NULL,
    role         VARCHAR(20) NOT NULL,
    left_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_chat_participant_role CHECK (role IN ('REQUESTER', 'OWNER')),
    CONSTRAINT uk_chat_participant_chat_room_id_member_id UNIQUE (chat_room_id, member_id),
    CONSTRAINT uk_chat_participant_chat_room_id_role UNIQUE (chat_room_id, role)
);
